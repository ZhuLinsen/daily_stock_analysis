export function getFieldOptionLabel(
  key: string,
  value: string,
  fallbackLabel?: string,
  locale: UiLanguage = 'zh',
): string {
  const map = locale === 'en'
    ? fieldOptionLabelMapEn[key]
    : locale === 'ko'
      ? fieldOptionLabelMapKo[key]
      : fieldOptionLabelMap[key];
  if (!map) {
    return fallbackLabel ?? value;
  }

  const byValue = map[normalizeOptionToken(value)];
  if (byValue) {
    return byValue;
  }

  if (fallbackLabel) {
    const byLabel = map[normalizeOptionToken(fallbackLabel)];
    if (byLabel) {
      return byLabel;
    }
  }

  return fallbackLabel ?? value;
}
